"""Generate src/avatar_data.cpp (the strip avatar bitmap) from a dsh-pet asset.

The island is a single self-contained .exe with no asset files at runtime, so the
"大肥鱼" avatar is baked into the binary as a raw RGBA8 array.  This script is the
only build-time step that needs Python/Pillow; the C++ side just reads the array.

    python tools/make_avatar.py "C:/Users/lenovo/Desktop/DSH-Pet/_internal/assets/
    big_blue_fat_fish/keai.png"

Steps: open -> crop to the alpha bounding box (so the character fills the box
instead of being surrounded by empty margin) -> scale the long side down ->
emit a C++ byte array.
"""

from __future__ import annotations

import argparse
import datetime
import pathlib
import sys

try:
    import numpy as np
    from PIL import Image, ImageDraw
except ImportError:  # pragma: no cover
    sys.exit("Pillow and numpy are required")

DEFAULT_SOURCE = (
    r"C:\Users\lenovo\Desktop\DSH-Pet\_internal\assets\big_blue_fat_fish\keai.png"
)


def key_out_white(img: Image.Image, threshold: int) -> Image.Image:
    """Make the white backdrop transparent.

    Every dsh-pet reaction image is an opaque artwork on a white/grey card, so the
    avatar has to be cut out before it can sit on the island's rounded pill.  Only
    the white that is *connected to the image border* is removed, so white parts
    inside the character (the maid apron, the skin highlights) survive: the dark
    line art around them stops the flood fill.
    """
    rgb = np.asarray(img.convert("RGB"), dtype=np.uint8)
    near_white = (rgb >= threshold).all(axis=2)
    h, w = near_white.shape

    # .copy() 必要：fromarray 出来的 L 图共享 numpy 缓冲且只读，floodfill 写不进去
    mask = Image.fromarray(np.where(near_white, 255, 0).astype(np.uint8), "L").copy()
    seeds = [(x, y) for x in range(w) for y in (0, h - 1)]
    seeds += [(x, y) for y in range(h) for x in (0, w - 1)]
    for point in seeds:
        if mask.getpixel(point) == 255:
            ImageDraw.floodfill(mask, point, 0, thresh=0)

    keyed = near_white & (np.asarray(mask) == 0)
    print(f"keyed out   : {int(keyed.sum())} px of backdrop (threshold>={threshold})")

    rgba = np.asarray(img, dtype=np.uint8).copy()
    rgba[..., 3] = np.where(keyed, 0, rgba[..., 3])
    return Image.fromarray(rgba, "RGBA")


def build_cpp(image: Image.Image, source: str, max_px: int) -> str:
    w, h = image.size
    data = image.tobytes()  # RGBA8, top-down
    assert len(data) == w * h * 4, "unexpected buffer length"

    lines: list[str] = []
    lines.append("// Generated by tools/make_avatar.py -- do not edit by hand.")
    lines.append(f"// source: {source}")
    lines.append(
        f"// {w}x{h} RGBA8, straight alpha, top-down. "
        f"Generated {datetime.date.today().isoformat()} (long side <= {max_px}px)."
    )
    lines.append("")
    lines.append('#include "avatar_data.h"')
    lines.append("")
    lines.append("namespace island_asset {")
    lines.append("namespace {")
    lines.append("")
    lines.append(f"constexpr int kAvatarW = {w};")
    lines.append(f"constexpr int kAvatarH = {h};")
    lines.append("")
    lines.append(f"const unsigned char kAvatarRgba[{w * h * 4}] = {{")

    row: list[str] = []
    for i, byte in enumerate(data):
        row.append(f"{byte:3d},")
        if len(row) == 20:
            lines.append("    " + "".join(row))
            row = []
    if row:
        lines.append("    " + "".join(row))

    lines.append("};")
    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const Image& AvatarImage() {")
    lines.append("    static const Image img{ kAvatarW, kAvatarH, kAvatarRgba };")
    lines.append("    return img;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace island_asset")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("source", nargs="?", default=DEFAULT_SOURCE)
    ap.add_argument("--max", type=int, default=64, help="long side of the baked bitmap")
    ap.add_argument("--key", type=int, default=235,
                    help="greyscale threshold for the white backdrop (0 disables keying)")
    ap.add_argument("--out", default="src/avatar_data.cpp")
    args = ap.parse_args()

    path = pathlib.Path(args.source)
    if not path.is_file():
        print(f"source image not found: {path}")
        return 1

    with Image.open(path) as raw:
        img = raw.convert("RGBA")
        print(f"source      : {path}  {raw.size[0]}x{raw.size[1]} mode={raw.mode}")

        alpha = img.getchannel("A")
        if alpha.getextrema()[0] == 255 and args.key > 0:
            img = key_out_white(img, args.key)
            alpha = img.getchannel("A")

        bbox = alpha.getbbox()
        print(f"alpha bbox  : {bbox}")
        if bbox:
            img = img.crop(bbox)

        w, h = img.size
        scale = args.max / max(w, h)
        if scale < 1.0:
            img = img.resize(
                (max(1, round(w * scale)), max(1, round(h * scale))),
                Image.LANCZOS,
            )
        print(f"baked       : {img.size[0]}x{img.size[1]}")

    text = build_cpp(img, str(path), args.max)
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote       : {out}  ({len(text)} bytes of C++ source)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
